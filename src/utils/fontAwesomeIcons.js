// Función para obtener el nombre de visualización de un icono
export function getIconDisplayName(icon) {
  const base = icon.split(' ').pop() || icon
  return base.replace('fa-', '').replace(/-/g, ' ').replace(/\b\w/g, l => l.toUpperCase())
}

